def normalize_region_key(region: str) -> str:
    return region.strip().lower().replace(" ", "").replace("　", "")


def resolve_region_center(region: str) -> tuple[float, float] | None:
    """지역 문자열 → (lat, lng). 매칭 실패 시 None."""
    key = normalize_region_key(region)
    if not key:
        return None
    if key in _JP_CENTERS:
        return _JP_CENTERS[key]
    # 부분 일치 (예: "오사카 시내", "오사카/교토")
    for alias, coords in _JP_CENTERS.items():
        if alias in key or key in alias:
            return coords
    return None


def centroid_of_places(places: list[tuple[float, float]]) -> tuple[float, float] | None:
    if not places:
        return None
    lat = sum(p[0] for p in places) / len(places)
    lng = sum(p[1] for p in places) / len(places)
    return lat, lng
